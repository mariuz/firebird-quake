// gen-frame-layouts.mjs – write src/framelayouts.js: the named frame runs of
// id Software's models ("stand1".."stand8", "run1".."run6"…), by model name.
// LibreQuake's models keep Quake's frame order and counts (progs.dat addresses
// frames by number) but name the frames "1", "2", …; the loader uses these
// layouts for any model whose frames carry no names.
//
//   node scripts/gen-frame-layouts.mjs [pak0.pak [pak1.pak]]   (defaults: public/pak/pak0.pak, pak1.pak)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Pak, PakSet } from '../src/pak.js';
import { Mdl } from '../src/mdl.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = (process.argv.length > 2 ? process.argv.slice(2) : ['public/pak/pak0.pak', 'public/pak/pak1.pak']).map((f) => path.resolve(root, f)).filter((f) => fs.existsSync(f));
const pak = new PakSet(files.map((f) => new Pak(fs.readFileSync(f).buffer)));
const out = {};
for (const name of pak.list('progs/', '.mdl')) {
  const m = new Mdl(pak.buffer(name), name);
  const anims = m.animations();
  if (anims.length === 1 && anims[0].name === 'frame') continue;   // nothing to learn
  out[name] = [m.frames.length, anims.map((a) => [a.name, a.first, a.count])];
}
const src = `// framelayouts.js – generated by scripts/gen-frame-layouts.mjs from the id models: for each model,
// its frame count and the named runs of frames. Used for models whose frames carry no names
// (LibreQuake's), which keep Quake's frame order so that any progs.dat can drive them.
export const FRAME_LAYOUTS = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(root, 'src/framelayouts.js'), src);
console.log(`src/framelayouts.js: ${Object.keys(out).length} models from ${files.map((f) => path.basename(f)).join(' + ')}`);
